# Lumbina launcher icon and TV banner: a film reel with a glowing hub, drawn as geometry and written
# as Android vector drawables (app/src/main/res/drawable), the banner as pictures (drawable-mdpi to
# drawable-xxxhdpi), and as SVG previews (scripts/design/preview).
#   python scripts/design/gen_icon.py
# The banner's pictures are drawn from its preview by ImageMagick (`magick`, with librsvg).
# Needs fontTools and Golos Text (OFL) for the banner's name, downloaded next to this script:
#   https://github.com/google/fonts/raw/main/ofl/golostext/GolosText%5Bwght%5D.ttf -> Golos.ttf
import math, os, subprocess, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

HERE = os.path.dirname(os.path.abspath(__file__))
RES = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'res')

AMBER = 'FFB547'
AMBER_DEEP = 'E0962C'
DARK = '0E1014'
TEXT = 'ECEEF2'


def f(v):
    s = f'{v:.2f}'.rstrip('0').rstrip('.')
    return s if s != '-0' else '0'


def circle(cx, cy, r):
    return (f'M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0'
            f'a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0z')


def reel_path(cx, cy, s):
    """Disc with six window cut-outs, a gap around the hub, and the hub; even-odd fill."""
    parts = [circle(cx, cy, 27 * s)]
    for k in range(6):
        a = math.radians(-90 + 60 * k)
        parts.append(circle(cx + 15.4 * s * math.cos(a), cy + 15.4 * s * math.sin(a), 5.7 * s))
    parts.append(circle(cx, cy, 8.8 * s))
    parts.append(circle(cx, cy, 6.6 * s))
    return ''.join(parts)


def flange_path(cx, cy, s):
    """A thin groove just inside the rim: ring between 24.4 and 25.4."""
    return circle(cx, cy, 25.4 * s) + circle(cx, cy, 24.4 * s)


# Shapes as (kind, data): ('fill', path, color, alpha, evenodd) or ('radial', path, cx, cy, r, stops)
def icon_layers(cx, cy, s):
    glow = ('radial', circle(cx, cy, 34 * s), cx, cy, 34 * s,
            [(0.70, AMBER, 0.55), (1.0, AMBER, 0.0)])
    reel = ('fill', reel_path(cx, cy, s), AMBER, 1.0, True)
    flange = ('fill', flange_path(cx, cy, s), AMBER_DEEP, 1.0, True)
    hub = ('radial', circle(cx, cy, 6.6 * s), cx, cy - 1.2 * s, 7.4 * s,
           [(0.0, 'FFF7E1', 1.0), (0.55, 'FFE3A6', 1.0), (1.0, 'FFC766', 1.0)])
    under = ('fill', circle(cx, cy, 26.6 * s), DARK, 1.0, False)  # the windows show dark, not the glow
    return [glow, under, reel, flange, hub]


def background_layers(w, h):
    return [('fill', f'M0,0h{w}v{h}h-{w}z', DARK, 1.0, False),
            ('radial', f'M0,0h{w}v{h}h-{w}z', w / 2, h / 2, max(w, h) / 2,
             [(0.0, '3A2A15', 1.0), (1.0, DARK, 1.0)])]


def text_layer(text, x, baseline, size, weight=600):
    font = TTFont(os.path.join(HERE, 'Golos.ttf'))
    font = instantiateVariableFont(font, {'wght': weight})
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font['head'].unitsPerEm
    k = size / upm
    layers, cursor = [], 0
    for ch in text:  # a path per letter keeps each one short
        g = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:.1f}'.rstrip('0').rstrip('.'))
        gs[g].draw(TransformPen(pen, (k, 0, 0, -k, x + cursor * k, baseline)))
        layers.append(('fill', pen.getCommands(), TEXT, 1.0, False))
        cursor += font['hmtx'][g][0]
    return layers, cursor * k


# ---- writers ----
def argb(color, alpha):
    return f'#{round(alpha * 255):02X}{color}'


def android(w, h, layers, comment):
    out = [f'<?xml version="1.0" encoding="utf-8"?>',
           f'<!-- {comment} Generated by scripts/design/gen_icon.py. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    xmlns:aapt="http://schemas.android.com/aapt"',
           f'    android:width="{f(w)}dp"', f'    android:height="{f(h)}dp"',
           f'    android:viewportWidth="{f(w)}"', f'    android:viewportHeight="{f(h)}">']
    for L in layers:
        if L[0] == 'fill':
            _, d, color, alpha, evenodd = L
            out.append('    <path')
            if evenodd:
                out.append('        android:fillType="evenOdd"')
            out.append(f'        android:fillColor="{argb(color, alpha)}"')
            out.append(f'        android:pathData="{d}" />')
        else:
            _, d, cx, cy, r, stops = L
            out.append(f'    <path android:pathData="{d}">')
            out.append('        <aapt:attr name="android:fillColor">')
            out.append(f'            <gradient android:type="radial" android:centerX="{f(cx)}" '
                       f'android:centerY="{f(cy)}" android:gradientRadius="{f(r)}">')
            for off, color, alpha in stops:
                out.append(f'                <item android:offset="{f(off)}" android:color="{argb(color, alpha)}" />')
            out.append('            </gradient>')
            out.append('        </aapt:attr>')
            out.append('    </path>')
    out.append('</vector>')
    return '\n'.join(out) + '\n'


def svg(w, h, layers, mask_circle=False):
    defs, body = [], []
    for i, L in enumerate(layers):
        if L[0] == 'fill':
            _, d, color, alpha, evenodd = L
            rule = ' fill-rule="evenodd"' if evenodd else ''
            body.append(f'<path d="{d}" fill="#{color}" fill-opacity="{alpha}"{rule}/>')
        else:
            _, d, cx, cy, r, stops = L
            st = ''.join(f'<stop offset="{off}" stop-color="#{c}" stop-opacity="{a}"/>' for off, c, a in stops)
            defs.append(f'<radialGradient id="g{i}" gradientUnits="userSpaceOnUse" cx="{cx}" cy="{cy}" r="{r}">{st}</radialGradient>')
            body.append(f'<path d="{d}" fill="url(#g{i})"/>')
    clip = ''
    if mask_circle:
        defs.append(f'<clipPath id="m"><circle cx="{w / 2}" cy="{h / 2}" r="{w / 2}"/></clipPath>')
        clip = ' clip-path="url(#m)"'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
            f'<defs>{"".join(defs)}</defs><g{clip}>{"".join(body)}</g></svg>')


def mono(layers):
    return [('fill', L[1], 'FFFFFF', 1.0, True) for L in layers if L[0] == 'fill' and L[2] == AMBER]


if __name__ == '__main__':
    os.makedirs(os.path.join(RES, 'drawable'), exist_ok=True)
    fg = icon_layers(54, 54, 1.08)
    bg = background_layers(108, 108)
    mn = mono(fg)

    # Banner: reel on the left, name on the right.
    bw, bh = 320, 180
    reel = icon_layers(80, 90, 1.6)
    word, width = text_layer('Lumbina', 142, 103, 38)
    banner = background_layers(bw, bh)[:1] + [('radial', f'M0,0h{bw}v{bh}h-{bw}z', 80, 90, 150,
                                               [(0.0, '33260F', 1.0), (1.0, DARK, 1.0)])] + reel + word

    files = {
        'drawable/ic_launcher_foreground.xml': android(108, 108, fg, 'Launcher icon, foreground: a film reel with a glowing hub.'),
        'drawable/ic_launcher_background.xml': android(108, 108, bg, 'Launcher icon, background: dark with a warm glow in the middle.'),
        'drawable/ic_launcher_monochrome.xml': android(108, 108, mn, 'Launcher icon, monochrome (themed icons): the reel alone.'),
    }
    for p, text in files.items():
        with open(os.path.join(RES, p), 'w', encoding='utf-8', newline='\n') as out:
            out.write(text)
    prev = os.path.join(HERE, 'preview')
    os.makedirs(prev, exist_ok=True)
    open(os.path.join(prev, 'icon-square.svg'), 'w').write(svg(108, 108, bg + fg))
    open(os.path.join(prev, 'icon-circle.svg'), 'w').write(svg(108, 108, bg + fg, mask_circle=True))
    open(os.path.join(prev, 'icon-mono.svg'), 'w').write(svg(108, 108, [('fill', 'M0,0h108v108h-108z', '3C4250', 1.0, False)] + [(L[0], L[1], 'E8E9EC', 1.0, True) for L in mn], mask_circle=True))
    open(os.path.join(prev, 'banner.svg'), 'w').write(svg(bw, bh, banner))
    # The banner as pictures of Android TV's 160x90 dp, as other apps have it: a vector's cached
    # bitmap goes to pixels when a launcher scales the focused banner up, and a bigger picture
    # shrunk to a launcher's tile without smoothing goes to steps (Android TV's own launcher, Mi Box 4).
    for density, scale in (('mdpi', 1), ('hdpi', 1.5), ('xhdpi', 2), ('xxhdpi', 3), ('xxxhdpi', 4)):
        folder = os.path.join(RES, f'drawable-{density}')
        os.makedirs(folder, exist_ok=True)
        size = f'{round(160 * scale)}x{round(90 * scale)}!'
        # Drawn four times bigger, then shrunk with a sharp filter.
        subprocess.run(['magick', '-background', 'none', '-density', str(round(96 * scale * 2)),
                        os.path.join(prev, 'banner.svg'), '-filter', 'Lanczos', '-resize', size, '-strip',
                        '-depth', '8', 'PNG32:' + os.path.join(folder, 'banner.png')], check=True)
    print('banner text ends at', round(142 + width, 1))
